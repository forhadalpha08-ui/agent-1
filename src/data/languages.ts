/**
 * Fallback / default is English when not set up, as specified by the prompt:
 * "when it not setuped it will active on english language"
 */
export const DEFAULT_LANGUAGE_ID = 'en';

export function getLanguage(idOrName?: string): TechLanguage {
  if (!idOrName) {
    return TECH_LANGUAGES.find((l) => l.id === DEFAULT_LANGUAGE_ID) || TECH_LANGUAGES[1];
  }
  // Check by ID
  const byId = TECH_LANGUAGES.find((l) => l.id.toLowerCase() === idOrName.toLowerCase());
  if (byId) return byId;

  // Check by name or country (for backward compatibility with 'Bangla' and 'English')
  if (idOrName.toLowerCase() === 'bangla' || idOrName.toLowerCase() === 'bengali') {
    return TECH_LANGUAGES[0]; // Bangladesh
  }
  if (idOrName.toLowerCase() === 'english') {
    return TECH_LANGUAGES[1]; // United States / English
  }

  const byCountry = TECH_LANGUAGES.find(
    (l) =>
      l.country.toLowerCase() === idOrName.toLowerCase() ||
      l.englishName.toLowerCase() === idOrName.toLowerCase() ||
      l.name.toLowerCase() === idOrName.toLowerCase()
  );

  return byCountry || TECH_LANGUAGES.find((l) => l.id === DEFAULT_LANGUAGE_ID) || TECH_LANGUAGES[1];
}

export function getInitialLanguage(): TechLanguage {
  if (typeof window === 'undefined') return getLanguage(DEFAULT_LANGUAGE_ID);
  try {
    const saved = localStorage.getItem('abdullah_ai_lang');
    if (saved) {
      return getLanguage(saved);
    }
  } catch (e) {
    // localStorage not accessible
  }
  // Default when not setuped is English
  return getLanguage(DEFAULT_LANGUAGE_ID);
}
